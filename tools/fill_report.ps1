# --------------------------------------------------------------------------
# Word 조작
# --------------------------------------------------------------------------

Write-Host "Word 시작..."
$word = New-Object -ComObject Word.Application
$word.Visible = $false
$word.DisplayAlerts = 0

try {
    $doc = $word.Documents.Open($output, $false, $false)

    # 1) 본문 지시문(10번째 문단부터 끝까지)을 아래에서부터 지운다.
    #    9번 문단인 첫 제목은 남겨 두고 그 뒤에 내용을 새로 붙인다.
    for ($i = $doc.Paragraphs.Count; $i -ge 10; $i--) {
        $doc.Paragraphs.Item($i).Range.Delete() | Out-Null
    }

    # 2) A Topic out of 5
    foreach ($line in $topic) {
        Add-Para $doc $line $BODY
    }

    # 3) Characteristics
    Add-Para $doc "Characteristics" $H1
    foreach ($line in $characteristicsIntro) {
        Add-Para $doc $line $BODY
    }
    Add-Para $doc $compare1Lead $BODY
    Add-Table $doc $compare1 "표 1. 후보 주제별 특징 비교"
    foreach ($line in $compare1Note) {
        Add-Para $doc $line $BODY
    }
    foreach ($line in $compare2Lead) {
        Add-Para $doc $line $BODY
    }
    Add-Table $doc $compare2 "표 2. 기존 방식과의 비교"
    Add-Para $doc $compare2Note $BODY

    # 4) Functionalities
    Add-Para $doc "Functionalities" $H1
    foreach ($line in $functionsIntro) {
        Add-Para $doc $line $BODY
    }
    Add-Table $doc $functionTable "표 3. 기능 목록"
    Add-Para $doc $functionTableNote $BODY

    foreach ($detail in $functionDetails) {
        Add-Para $doc $detail.Heading $H2
        foreach ($line in $detail.Lines) {
            Add-Para $doc $line $BODY
        }
    }

    # 5) 제목과 저자 줄
    #    Range.Text 로 바로 덮어쓰면 문단 기호까지 지워져 다음 문단과 붙어 버린다.
    #    문단 기호 한 글자를 범위에서 빼고 바꾼다.
    Set-ParagraphText $doc 3 "$Name, $StudentId"
    Set-ParagraphText $doc 1 $AppName

    $doc.Save()
    Write-Host "생성 완료: $output"
    Write-Host "문단 수: $($doc.Paragraphs.Count), 표: $($doc.Tables.Count), 페이지: $($doc.ComputeStatistics(2))"

    $doc.Close($false)
}
finally {
    $word.Quit()
    [void][System.Runtime.InteropServices.Marshal]::ReleaseComObject($word)
    [GC]::Collect()
}
