package moneynote.service;

import java.io.IOException;
import java.time.LocalDate;
import java.time.YearMonth;
import java.util.ArrayList;
import java.util.List;
import moneynote.model.Category;
import moneynote.model.RecurringRule;
import moneynote.model.Transaction;
import moneynote.model.TransactionType;
import moneynote.repository.RecurringRepository;
import moneynote.util.DateUtil;

/**
 * 고정 지출 규칙을 관리하고 매월 거래로 만들어 준다. (F9)
 *
 * <p>거래 생성은 반드시 {@link LedgerService#register} 를 거친다. 사용자가 직접 등록할 때와
 * 같은 검증을 받게 하기 위해서다.
 */
public class RecurringService {

    /** 자동 생성 거래의 결제수단. 고정 지출은 대부분 자동이체이므로 고정값으로 둔다. */
    static final String PAYMENT = "계좌이체";

    private final RecurringRepository rules;
    private final LedgerService ledger;

    /**
     * 서비스를 만든다.
     *
     * @param rules  규칙 저장소
     * @param ledger 거래 등록과 분류 조회에 쓰는 서비스
     */
    public RecurringService(RecurringRepository rules, LedgerService ledger) {
        this.rules = rules;
        this.ledger = ledger;
    }

    /**
     * 등록 순서대로 모든 규칙.
     *
     * @return 등록 순서대로 모든 규칙
     */
    public List<RecurringRule> rules() {
        return rules.findAll();
    }

    /**
     * 규칙을 추가한다. 추가한 규칙은 다음 시작부터 거래를 만든다.
     *
     * @param categoryId 지출 분류 id
     * @param amount     매월 금액(원), 0보다 커야 한다
     * @param dayOfMonth 매월 결제일, 1~31
     * @param memo       생성될 거래의 메모
     * @return 추가된 규칙
     * @throws IllegalArgumentException 금액, 결제일, 분류가 올바르지 않은 경우
     */
    public RecurringRule addRule(int categoryId, long amount, int dayOfMonth, String memo) {
        if (amount <= 0) {
            throw new IllegalArgumentException("금액은 0보다 커야 합니다.");
        }
        if (dayOfMonth < 1 || dayOfMonth > 31) {
            throw new IllegalArgumentException("결제일은 1일부터 31일 사이여야 합니다.");
        }
        Category category = ledger.categories().findById(categoryId)
                .orElseThrow(() -> new IllegalArgumentException("분류를 선택하세요."));
        if (category.type() != TransactionType.EXPENSE) {
            throw new IllegalArgumentException("고정 지출에는 지출 분류만 쓸 수 있습니다.");
        }
        return rules.add(categoryId, amount, dayOfMonth, memo);
    }

    /**
     * 규칙을 켜거나 끈다. 끈 규칙은 다음 시작부터 거래를 만들지 않는다.
     *
     * @param ruleId 규칙 id
     * @param active 켜려면 true
     * @throws IllegalArgumentException 규칙이 없는 경우
     */
    public void setActive(int ruleId, boolean active) {
        find(ruleId).setActive(active);
    }

    /**
     * 규칙을 지운다. 이미 만든 거래는 그대로 남는다.
     *
     * @param ruleId 규칙 id
     */
    public void deleteRule(int ruleId) {
        rules.remove(ruleId);
    }

    /**
     * 분류를 쓰는 규칙 수. 분류를 지우기 전에 확인한다.
     *
     * @param categoryId 분류 id
     * @return 이 분류를 쓰는 규칙 수
     */
    public int countByCategory(int categoryId) {
        return rules.countByCategory(categoryId);
    }

    /**
     * 프로그램 시작 시 호출한다. 활성 규칙 중 그 달에 아직 만들지 않은 것을 거래로 만든다.
     *
     * <p>마지막 생성 월이 그 달 이후인 규칙은 건너뛰므로 여러 번 불러도 중복이 생기지 않는다.
     * 그 달에 없는 결제일(2월 31일 등)은 마지막 날로 대체한다. 분류가 지워져 검증에 실패한
     * 규칙은 건너뛰고 생성 기록도 남기지 않는다.
     *
     * @param month 거래를 만들 달, 보통 이번 달
     * @return 이번에 생성된 거래 목록
     */
    public List<Transaction> generateFor(YearMonth month) {
        List<Transaction> created = new ArrayList<>();
        for (RecurringRule rule : rules.findAll()) {
            if (!rule.active()) {
                continue;
            }
            if (rule.lastGenerated() != null && !rule.lastGenerated().isBefore(month)) {
                continue;
            }
            LocalDate date = DateUtil.dayInMonth(month, rule.dayOfMonth());
            try {
                Transaction t = ledger.register(date, TransactionType.EXPENSE, rule.amount(),
                        rule.categoryId(), PAYMENT, rule.memo());
                t.setAutoGenerated(true);
                rule.setLastGenerated(month);
                created.add(t);
            } catch (IllegalArgumentException e) {
                // 분류가 사라진 규칙. 시작을 막지 않도록 이 규칙만 건너뛴다.
            }
        }
        return created;
    }

    /**
     * 규칙을 파일에 쓴다.
     *
     * @throws IOException 파일을 쓰지 못한 경우
     */
    public void save() throws IOException {
        rules.save();
    }

    private RecurringRule find(int ruleId) {
        return rules.findById(ruleId)
                .orElseThrow(() -> new IllegalArgumentException("규칙을 찾을 수 없습니다: " + ruleId));
    }
}
