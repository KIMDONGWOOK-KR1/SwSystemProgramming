package moneynote.model;

import java.time.LocalDate;

/**
 * 거래 한 건.
 *
 * <p>금액은 원 단위 정수(long)로 다룬다. double을 쓰면 합계를 반복할 때 오차가
 * 누적되는데, 가계부는 1원의 오차도 허용하지 않기 때문이다.
 */
public class Transaction {

    private final int id;
    private LocalDate date;
    private TransactionType type;
    /** 원 단위. 부호는 type이 결정하므로 항상 양수로 저장한다. */
    private long amount;
    private int categoryId;
    private String payment;
    private String memo;
    /** 고정 지출 규칙(F9)에 의해 자동 생성된 거래인지 여부. */
    private boolean autoGenerated;

    /**
     * 거래를 만든다. 값 검증은 서비스 계층이 먼저 한다.
     *
     * @param id         저장소가 붙인 고유 번호
     * @param date       거래 날짜
     * @param type       수입 또는 지출
     * @param amount     금액(원), 항상 양수
     * @param categoryId 분류 id
     * @param payment    결제수단 (현금, 카드, 계좌이체)
     * @param memo       메모, null 이면 빈 문자열로 둔다
     */
    public Transaction(int id, LocalDate date, TransactionType type, long amount,
                       int categoryId, String payment, String memo) {
        this.id = id;
        this.date = date;
        this.type = type;
        this.amount = amount;
        this.categoryId = categoryId;
        this.payment = payment;
        this.memo = memo == null ? "" : memo;
    }

    /**
     * 거래 id.
     *
     * @return 거래 id
     */
    public int id() {
        return id;
    }

    /**
     * 거래 날짜.
     *
     * @return 거래 날짜
     */
    public LocalDate date() {
        return date;
    }

    /**
     * 거래 날짜를 바꾼다.
     *
     * @param date 새 거래 날짜
     */
    public void setDate(LocalDate date) {
        this.date = date;
    }

    /**
     * 수입 또는 지출.
     *
     * @return 수입 또는 지출
     */
    public TransactionType type() {
        return type;
    }

    /**
     * 거래 유형을 바꾼다.
     *
     * @param type 새 유형
     */
    public void setType(TransactionType type) {
        this.type = type;
    }

    /**
     * 금액(원), 항상 양수.
     *
     * @return 금액(원), 항상 양수
     */
    public long amount() {
        return amount;
    }

    /**
     * 금액을 바꾼다.
     *
     * @param amount 새 금액(원)
     */
    public void setAmount(long amount) {
        this.amount = amount;
    }

    /**
     * 분류 id.
     *
     * @return 분류 id
     */
    public int categoryId() {
        return categoryId;
    }

    /**
     * 분류를 바꾼다.
     *
     * @param categoryId 새 분류 id
     */
    public void setCategoryId(int categoryId) {
        this.categoryId = categoryId;
    }

    /**
     * 결제수단.
     *
     * @return 결제수단
     */
    public String payment() {
        return payment;
    }

    /**
     * 결제수단을 바꾼다.
     *
     * @param payment 새 결제수단
     */
    public void setPayment(String payment) {
        this.payment = payment;
    }

    /**
     * 메모, 없으면 빈 문자열.
     *
     * @return 메모, 없으면 빈 문자열
     */
    public String memo() {
        return memo;
    }

    /**
     * 메모를 바꾼다.
     *
     * @param memo 새 메모, null 이면 빈 문자열로 둔다
     */
    public void setMemo(String memo) {
        this.memo = memo == null ? "" : memo;
    }

    /**
     * 고정 지출 규칙이 자동으로 만든 거래이면 true.
     *
     * @return 고정 지출 규칙이 자동으로 만든 거래이면 true
     */
    public boolean autoGenerated() {
        return autoGenerated;
    }

    /**
     * 자동 생성 거래인지 표시한다.
     *
     * @param autoGenerated 자동 생성 거래 여부
     */
    public void setAutoGenerated(boolean autoGenerated) {
        this.autoGenerated = autoGenerated;
    }

    /**
     * 수입은 양수, 지출은 음수로 본 부호 있는 금액. 잔액 계산에 쓴다.
     *
     * @return 부호 있는 금액(원)
     */
    public long signedAmount() {
        return type == TransactionType.INCOME ? amount : -amount;
    }
}
