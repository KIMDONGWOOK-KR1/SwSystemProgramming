package moneynote.repository;

import java.io.IOException;
import java.nio.file.Path;
import java.time.LocalDate;
import java.util.ArrayList;
import java.util.List;
import java.util.Optional;
import moneynote.model.Transaction;
import moneynote.model.TransactionType;
import moneynote.util.DateUtil;

/** 거래 저장소. 메모리 목록을 원본으로 두고 CSV로 영속화한다. (F1, F2, F10) */
public class TransactionRepository {

    private static final String[] HEADER = {
        "id", "date", "type", "amount", "categoryId", "payment", "memo", "auto"
    };

    private final Path file;
    private final List<Transaction> items = new ArrayList<>();
    private int nextId = 1;
    /** 읽는 중 형식이 깨져 건너뛴 행 번호. 사용자에게 알리기 위해 남긴다. */
    private final List<Integer> skippedRows = new ArrayList<>();

    /**
     * 저장소를 만든다. 파일은 {@link #load()} 를 부를 때 읽는다.
     *
     * @param file 저장할 CSV 파일 경로
     */
    public TransactionRepository(Path file) {
        this.file = file;
    }

    /**
     * 등록 순서대로 모든 거래 (읽기 전용).
     *
     * @return 등록 순서대로 모든 거래 (읽기 전용)
     */
    public List<Transaction> findAll() {
        return List.copyOf(items);
    }

    /**
     * id로 거래를 찾는다.
     *
     * @param id 거래 id
     * @return 거래, 없으면 빈 값
     */
    public Optional<Transaction> findById(int id) {
        return items.stream().filter(t -> t.id() == id).findFirst();
    }

    /**
     * 분류를 쓰는 거래 수.
     *
     * @param categoryId 분류 id
     * @return 이 분류를 쓰는 거래 수
     */
    public int countByCategory(int categoryId) {
        return (int) items.stream().filter(t -> t.categoryId() == categoryId).count();
    }

    /**
     * 새 id를 붙여 거래를 추가한다. 값 검증은 서비스 계층이 한다.
     *
     * @param date       거래 날짜
     * @param type       수입 또는 지출
     * @param amount     금액(원)
     * @param categoryId 분류 id
     * @param payment    결제수단
     * @param memo       메모
     * @return 추가된 거래
     */
    public Transaction add(LocalDate date, TransactionType type, long amount,
                           int categoryId, String payment, String memo) {
        Transaction t = new Transaction(nextId++, date, type, amount, categoryId, payment, memo);
        items.add(t);
        return t;
    }

    /**
     * 거래를 지운다. 없으면 아무 일도 하지 않는다.
     *
     * @param id 지울 거래 id
     */
    public void delete(int id) {
        items.removeIf(t -> t.id() == id);
    }

    /**
     * 형식이 깨져 건너뛴 행.
     *
     * @return 마지막 {@link #load()} 에서 건너뛴 행 번호(헤더를 1행으로 센다)
     */
    public List<Integer> skippedRows() {
        return List.copyOf(skippedRows);
    }

    /**
     * 파일에서 읽는다. 형식이 깨진 행은 건너뛰고 {@link #skippedRows()} 에 남긴다.
     *
     * @throws IOException 파일을 읽지 못한 경우
     */
    public void load() throws IOException {
        items.clear();
        skippedRows.clear();
        List<String[]> rows = CsvStore.read(file);
        for (int i = 0; i < rows.size(); i++) {
            String[] row = rows.get(i);
            try {
                int id = Integer.parseInt(row[0]);
                Transaction t = new Transaction(
                        id,
                        DateUtil.parse(row[1]),
                        TransactionType.valueOf(row[2]),
                        Long.parseLong(row[3]),
                        Integer.parseInt(row[4]),
                        row[5],
                        row[6]);
                t.setAutoGenerated(row.length > 7 && Boolean.parseBoolean(row[7]));
                items.add(t);
                nextId = Math.max(nextId, id + 1);
            } catch (RuntimeException e) {
                // 손상된 행은 건너뛰고 나머지는 정상 처리한다. 행 번호는 헤더를 감안해 +2.
                skippedRows.add(i + 2);
            }
        }
    }

    /**
     * 모든 항목을 파일에 쓴다.
     *
     * @throws IOException 파일을 쓰지 못한 경우
     */
    public void save() throws IOException {
        List<String[]> rows = new ArrayList<>();
        for (Transaction t : items) {
            rows.add(new String[] {
                String.valueOf(t.id()),
                DateUtil.format(t.date()),
                t.type().name(),
                String.valueOf(t.amount()),
                String.valueOf(t.categoryId()),
                t.payment(),
                t.memo(),
                String.valueOf(t.autoGenerated())
            });
        }
        CsvStore.write(file, HEADER, rows);
    }
}
